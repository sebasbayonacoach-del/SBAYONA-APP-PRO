import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { hasScopedState, hasOnboardedScopedProfile } from "../js/sync/identity.js";

const id = "00000000-0000-4000-8000-000000000001";
const other = "00000000-0000-4000-8000-000000000002";
const key = (uid) => "bayona.user." + uid + "::bayona.save.v2";
const map = new Map();
const store = { getItem(k) { return map.get(k) ?? null; } };
let passes = 0;
