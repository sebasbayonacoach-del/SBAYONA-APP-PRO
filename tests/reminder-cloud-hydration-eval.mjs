import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { reminderPreferencesFromCloud, notificationPreferenceRow } from "../js/notifications/daily.js";

let passed = 0;
const ok = (condition, label) => { assert.ok(condition, label); passed++; };
const timestamp = "2026-11-19T14:00:00.000Z";
const local = { asked: true, morning: false, preTraining: false, evening: true, preTrainingAt: "", updatedAt: "2026-11-19T13:00:00.000Z" };
const remote = { asked: true, morning: true, pre_training: true, evening: false, pre_training_at: "18:20", updated_at: timestamp };
const hydrated = reminderPreferencesFromCloud(local, remote);
ok(hydrated?.morning === true && hydrated?.preTraining === true && hydrated?.evening === false, "aplica flags de otra sesión");
ok(hydrated.preTrainingAt === "18:20", "aplica la hora guardada");
ok(hydrated.updatedAt === timestamp, "preserva marca temporal de servidor");
ok(local.morning === false && local.preTraining === false, "no muta el estado anterior");
ok(reminderPreferencesFromCloud(local, null) === null, "sin fila no altera preferencias locales");
ok(reminderPreferencesFromCloud(local, { ...remote, updated_at: "" }) === null, "sin timestamp remoto no aplica");
ok(reminderPreferencesFromCloud({ ...local, updatedAt: timestamp }, remote) === null, "cambio local igual de reciente no se sobrescribe");
ok(reminderPreferencesFromCloud({ ...local, updatedAt: "2026-11-19T15:00:00.000Z" }, remote) === null, "edición offline posterior no se pierde");
const off = reminderPreferencesFromCloud({}, { ...remote, asked: false, morning: false, pre_training: false, evening: false, pre_training_at: "19:00" });
ok(off.asked === false && off.morning === false && off.evening === false && off.preTraining === false, "respeta baja remota");
ok(off.preTrainingAt === "", "no conserva hora de entrenamiento desactivado");
ok(reminderPreferencesFromCloud({}, { ...remote, pre_training_at: "99:99" }).preTrainingAt === "", "descarta hora malformada");
ok(reminderPreferencesFromCloud({ custom: "local" }, { ...remote, body: "dato de salud", url: "https://evil.example" }).custom === "local", "mantiene campos locales desconocidos");
ok(!("body" in hydrated) && !("url" in hydrated), "no mezcla payload arbitrario en perfil");
ok(!("consent_enabled" in hydrated), "hidratar ajustes locales no habilita Web Push");
const row = notificationPreferenceRow("00000000-0000-4000-8000-000000000001", hydrated, "Europe/Madrid", new Date(hydrated.updatedAt));
ok(row.updated_at === timestamp && row.consent_enabled === false, "roundtrip mantiene fecha y consentimiento desactivado");
const source = readFileSync(new URL("../js/notifications/daily.js", import.meta.url), "utf8");
ok(source.includes('currentUser()?.id !== uid'), "verifica identidad al acabar lectura remota");
ok(source.includes('user_id: "eq." + uid'), "consulta solo la cuenta actual");
ok(source.includes("void hydrateFromCloud();"), "recupera al abrir app");
ok(source.includes('window.addEventListener("focus", onFocus)'), "revalida al volver al dispositivo");
console.log("APP 7.0 · " + passed + " comprobaciones de hidratación multi-dispositivo: PASS");
